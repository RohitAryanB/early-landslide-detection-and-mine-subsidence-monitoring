// Helper to generate 24 hours of consistent historical data
function generateHistory(
  baseTilt: number,
  baseVib: number,
  baseDisp: number,
  baseCrack: number,
  baseMoist: number,
  basePore: number,
  baseRain: number,
  baseBat: number
) {
  const history = [];
  const now = Date.now();
  for (let i = 24; i >= 0; i--) {
    const time = new Date(now - i * 3600 * 1000).toISOString();
    const progress = (24 - i) / 24;
    // Add subtle realistic variations
    const noise = Math.sin(i * 0.8) * 0.05;
    history.push({
      timestamp: time,
      tilt: Math.max(0, +(baseTilt - (1 - progress) * (baseTilt * 0.2) + noise).toFixed(3)),
      vibration: Math.max(0.05, +(baseVib + Math.sin(i * 1.5) * 0.15).toFixed(2)),
      displacement: Math.max(0, +(baseDisp - (1 - progress) * (baseDisp * 0.3) + noise * 0.5).toFixed(2)),
      crackWidth: Math.max(0, +(baseCrack - (1 - progress) * (baseCrack * 0.25) + noise * 0.2).toFixed(2)),
      soilMoisture: Math.max(5, +(baseMoist + Math.cos(i * 0.3) * 1.5).toFixed(1)),
      porePressure: Math.max(2, +(basePore + Math.cos(i * 0.3) * 1.2).toFixed(1)),
      rainfall: Math.max(0, +(baseRain + Math.max(0, Math.sin(i * 0.4) * 2)).toFixed(1)),
      battery: Math.min(100, Math.max(10, +(baseBat + (24 - i) * 0.05).toFixed(1)))
    });
  }
  return history;
}

